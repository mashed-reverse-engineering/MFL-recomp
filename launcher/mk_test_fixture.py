#!/usr/bin/env python3
"""mk_test_fixture.py <out dir>: the fixture pair of test_logic for the release layout with the mflng/ sub folder (W17 LAYOUT C).
Writes <out dir>/MFLng-<TAG>.zip (the layout release.yml packs: the three exes, mflrw.dll and INSTALL.txt at the top; the backend DLLs,
BUILDINFO.txt, LICENSES/ and SHA256SUMS (listing zip names) in mflng/; the file contents are generated bytes, no real program) and
<out dir>/releases.json (one pre-release of that tag whose asset digest is the zip's SHA-256, the shape of the GitHub releases API answer).
Same bytes on every run.  Then:
    launcher/build.sh test <out dir> && <out dir>/test_logic <out dir>/releases.json <out dir>/MFLng-<TAG>.zip <TAG>"""
import hashlib, json, os, sys, zipfile

TAG = "r20990101-0000-abcdef0"
TOP = ["MFLng.exe", "MFLng.nofix.exe", "MFLng-launch.exe", "mflrw.dll"]
SUB = ["mfl_audio_miniaudio.dll", "mfl_video_ffmpeg.dll", "avformat-61.dll", "avcodec-61.dll", "avutil-59.dll", "swscale-8.dll"]


def noise(name, n=4096):
    """n bytes that depend only on the name (not compressible: the entry keeps a body the flipped-byte check can hit)"""
    out, h = b"", name.encode()
    while len(out) < n:
        h = hashlib.sha256(h).digest(); out += h
    return out[:n]


def main(out):
    os.makedirs(out, exist_ok=True)
    files = {"INSTALL.txt": b"fixture install text\n" * 8, "mflng/BUILDINFO.txt": ("cl 19.44\nrelease %s prerelease\n" % TAG).encode(),
             "mflng/LICENSES/zlib.txt": b"fixture licence text\n" * 8}
    files.update({f: noise(f) for f in TOP})
    files.update({"mflng/" + f: noise(f) for f in SUB})
    files["mflng/SHA256SUMS"] = "".join("%s  %s\n" % (hashlib.sha256(files[k]).hexdigest(), k) for k in sorted(files)).encode()
    zp = os.path.join(out, "MFLng-%s.zip" % TAG)
    with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
        for k in ["mflng/", "mflng/LICENSES/"] + sorted(files):      # folder entries as `zip -r` writes them
            z.writestr(zipfile.ZipInfo(k, (2099, 1, 1, 0, 0, 0)), files.get(k, b""), zipfile.ZIP_DEFLATED if k in files else zipfile.ZIP_STORED)
    name = os.path.basename(zp)
    rel = [{"tag_name": TAG, "draft": False, "prerelease": True, "body": "Fixture release for test_logic (mflng sub folder layout).",
            "assets": [{"name": name.replace(".zip", "-maps.zip"), "digest": None, "browser_download_url": "https://example.invalid/" + name.replace(".zip", "-maps.zip")},
                       {"name": name, "digest": "sha256:" + hashlib.sha256(open(zp, "rb").read()).hexdigest(), "browser_download_url": "https://example.invalid/" + name}]}]
    json.dump(rel, open(os.path.join(out, "releases.json"), "w"), indent=1)
    print("%s %s/releases.json tag %s" % (zp, out, TAG))


if __name__ == "__main__":
    if len(sys.argv) != 2: sys.exit(__doc__)
    main(sys.argv[1])
