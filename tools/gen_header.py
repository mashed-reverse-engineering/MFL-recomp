#!/usr/bin/env python3
"""Generate a C header (mfl_types.h) from the struct specs used by ApplyStructs.java.
Usage: gen_header.py <out.h> <spec.txt> [<spec.txt> ...]
Fields are laid out at their offsets with explicit padding (char _padNNN[]), so sizeof matches the spec.
Types: u8 u16 i16 u32 i32 f32 char, X[N], and other spec structs. Spec comments become C comments."""
import re, sys

BASE = {"u8": ("unsigned char", 1), "u16": ("unsigned short", 2), "i16": ("short", 2), "u32": ("unsigned int", 4),
        "i32": ("int", 4), "f32": ("float", 4), "char": ("char", 1)}


def parse(paths):
    structs, order, cur = {}, [], None
    for p in paths:
        for line in open(p, encoding="utf-8"):
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split(",", 4)
            if parts[0] == "struct":
                cur = {"name": parts[1], "size": int(parts[2], 0), "fields": []}
                structs[parts[1]] = cur
                order.append(parts[1])
            elif parts[0] == "field" and cur is not None:
                cur["fields"].append((int(parts[1], 0), parts[2], parts[3], parts[4] if len(parts) > 4 else ""))
    return structs, order


def type_size(t, structs):
    m = re.match(r"^(\w+)(?:\[(\d+)\])?$", t)
    name, n = m.group(1), int(m.group(2) or 1)
    if name in BASE:
        return BASE[name][1] * n
    return structs[name]["size"] * n


def c_decl(t, name):
    m = re.match(r"^(\w+)(?:\[(\d+)\])?$", t)
    base, n = m.group(1), m.group(2)
    ctype = BASE[base][0] if base in BASE else "struct %s" % base
    return "%s %s%s;" % (ctype, name, "[%s]" % n if n else "")


def usable(structs):
    """structs whose field types are all known (others reference the RenderWare SDK types and are skipped)."""
    ok = {}
    def check(n, stack=()):
        if n in ok:
            return ok[n]
        if n in stack:
            return False
        good = True
        for off, t, fname, c in structs[n]["fields"]:
            base = re.match(r"^(\w+)", t).group(1)
            if base in BASE:
                continue
            if base not in structs or not check(base, stack + (n,)):
                good = False
        ok[n] = good
        return good
    return {n for n in structs if check(n)}


def emit(structs, order, out):
    good = usable(structs)
    skipped = [n for n in order if n not in good]
    order = [n for n in order if n in good]
    out.write("/* Generated by ghidra/tools/gen_header.py from the ApplyStructs specs. Do not edit. */\n#ifndef MFL_TYPES_H\n#define MFL_TYPES_H\n\n")
    for n in order:
        out.write("struct %s;\n" % n)
    out.write("\n")
    if skipped:
        out.write("/* skipped (need RenderWare SDK types): %s */\n\n" % ", ".join(skipped))
    done = set()
    def write(n):
        if n in done:
            return
        s = structs[n]
        for off, t, fname, c in s["fields"]:
            base = re.match(r"^(\w+)", t).group(1)
            if base in structs:
                write(base)
        done.add(n)
        out.write("#pragma pack(push, 1)\nstruct %s { /* 0x%X bytes */\n" % (n, s["size"]))
        pos = 0
        for off, t, fname, c in sorted(s["fields"], key=lambda f: f[0]):
            if off < pos:
                out.write("    /* %s at 0x%X overlaps the previous field, skipped */\n" % (fname, off))
                continue
            if off > pos:
                out.write("    char _pad%03X[0x%X];\n" % (pos, off - pos))
            cm = " /* +0x%X %s */" % (off, c.strip().strip('"')[:70].replace("*/", "* /")) if c else " /* +0x%X */" % off
            out.write("    %s%s\n" % (c_decl(t, fname), cm))
            pos = off + type_size(t, structs)
        if pos < s["size"]:
            out.write("    char _pad%03X[0x%X];\n" % (pos, s["size"] - pos))
        out.write("};\n#pragma pack(pop)\n")
        # compile time checks (the idea of reccmp's DECOMP_SIZE_ASSERT): a wrong size or offset breaks the build instead of the game
        out.write("MFL_STATIC_ASSERT(%s_size, sizeof(struct %s) == 0x%X);\n" % (n, n, s["size"]))
        pos2 = 0
        for off, t, fname, c in sorted(s["fields"], key=lambda f: f[0]):
            if off < pos2:
                continue
            out.write("MFL_STATIC_ASSERT(%s_%s, (int)&((struct %s *)0)->%s == 0x%X);\n" % (n, fname, n, fname, off))
            pos2 = off + type_size(t, structs)
        out.write("\n")
    out.write("#define MFL_STATIC_ASSERT(name, cond) typedef char mfl_assert_##name[(cond) ? 1 : -1]\n\n")
    for n in order:
        write(n)
    out.write("#endif\n")


if __name__ == "__main__":
    structs, order = parse(sys.argv[2:])
    with open(sys.argv[1], "w") as f:
        emit(structs, order, f)
    print("wrote", sys.argv[1], len(order), "structs")
