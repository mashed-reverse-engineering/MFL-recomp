#!/usr/bin/env python3
"""Build a compilable translation unit from the named decompilation (ghidra/output/named/MFL_app_named.c).
Usage: gen_tu.py <out.c> <decls.h> <first VA hex> <last VA hex> [skip-regs]
Functions that use register pseudo variables (in_EAX, unaff_ESI, extraout_*) are skipped (listed in the header comment)."""
import re, sys

out, decls, lo, hi = sys.argv[1], sys.argv[2], int(sys.argv[3], 16), int(sys.argv[4], 16)
text = open(__import__("os").path.join(__import__("os").path.dirname(__import__("os").path.abspath(__file__)), "..", "output", "named", "MFL_app_named.c"), errors="replace").read()
funcs = []
for m in re.finditer(r"// ==== (\S+) @ ([0-9a-f]+)\n(.*?)(?=\n// ==== |\Z)", text, re.S):
    n, a, body = m.group(1), int(m.group(2), 16), m.group(3)
    if lo <= a <= hi:
        funcs.append((n, a, body))
skipped, kept = [], []
for n, a, body in funcs:
    if re.search(r"\b(in_[A-Z]{2,3}|unaff_[A-Za-z]+|extraout_\w+|stack0x\w+|param_\d+_00\w+|unaff_retaddr|POPCOUNT|SBORROW\d|CARRY\d|halt_baddata)\b", body):
        skipped.append(n)
    else:
        kept.append((n, a, body))
defined = {n for n, _, _ in kept}
used = set(re.findall(r'[A-Za-z_]\w*', ' '.join(b for _, _, b in kept)))
decl_lines = []
for l in open(decls, errors="replace"):
    m = re.search(r"extern .*?(\w+)\(", l)
    nm = m.group(1) if m else None
    mm = re.search(r"extern [^(]*?(\w+)(\[\d+\])*;", l)
    if nm in defined:
        continue
    mname = re.search(r'extern .*?([A-Za-z_]\w*)(\(| *\[|;)', l)
    if not mname or mname.group(1) not in used:
        continue
    decl_lines.append(l)
with open(out, "w") as f:
    f.write("/* generated by ghidra/tools/gen_tu.py: %d functions, skipped (register pseudo variables): %s */\n" % (len(kept), " ".join(skipped)))
    f.write('#include "prelude.h"\n#include "ghidra_types.h"\n')
    f.write("".join(decl_lines))
    for n, a, body in kept:
        body = body.replace("__thiscall", "__fastcall")
        f.write("\n/* %s @ %08x */\n%s\n" % (n, a, body))
print("kept", len(kept), "skipped", len(skipped), file=sys.stderr)
