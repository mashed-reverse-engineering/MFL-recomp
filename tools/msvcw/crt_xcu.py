#!/usr/bin/env python3
"""crt_xcu.py <exe | slots.txt> <out.c>: W16 V143 item 2 (CC=v143 LIB_CRT=v143md only).  The game's C initialiser table __xc_a..__xc_z (src/symbols.txt,
0x5fb000..0x5fb038 in .data) as a .CRT$XCU array for the v143 CRT start-up (_initterm), entries in the original table order.  Left out: the
two end markers, zero slots and __security_init_cookie (the v143 start-up sets the cookie itself).  The functions are named func_0x<VA>
(mkobj defines them at that address: the entry jmp to our C).  Exits 1 unless exactly 12 entries remain (INV 6).
V143c9: entries inside dead code (tools/delink/dshow_dead.txt always = A7; rw_dead.txt with DROP_RW) are left out, as the VC7 link zeroes
those table slots (globgen DROP_DSHOW / DROP_RW, _initterm skips NULL).  Today all 12 are DirectShow static initialisers: the table is empty."""
import os, struct, sys

G = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
WANT = 12


def dead():
    out = []
    for f in ["dshow_dead.txt"] + (["rw_dead.txt"] if os.environ.get("DROP_RW") else []):
        for l in open(os.path.join(G, "tools", "delink", f)):
            p = l.split()
            if p and not l.startswith("#"): out.append((int(p[0], 16), int(p[0], 16) + int(p[1])))
    return out


def table(exe):
    if exe.endswith(".txt"):      # SK2 W16 NOEXE: the slot values committed as text (data/link/crt_xcu.txt, tools/ci/link_tables.py emit), one hex VA per line
        return [int(l.split()[0], 16) for l in open(exe) if l.strip() and not l.startswith("#")]
    s = {l.split()[0]: int(l.split()[1], 16) for l in open(os.path.join(G, "src", "symbols.txt"))
         if len(l.split()) >= 2 and l.split()[0] in ("__xc_a", "__xc_z", "__security_init_cookie")}
    d = open(exe, "rb").read(); e = struct.unpack_from("<I", d, 0x3c)[0]
    ns, osz = struct.unpack_from("<H", d, e + 6)[0], struct.unpack_from("<H", d, e + 20)[0]
    base = struct.unpack_from("<I", d, e + 52)[0]
    for k in range(ns):
        vs, va, rs, rp = struct.unpack_from("<IIII", d, e + 24 + osz + 40 * k + 8)
        if base + va <= s["__xc_a"] < base + va + rs:
            words = struct.unpack_from("<%dI" % ((s["__xc_z"] - s["__xc_a"]) // 4 - 1), d, rp + s["__xc_a"] + 4 - base - va)
            return [w for w in words if w and w != s["__security_init_cookie"]]
    sys.exit("crt_xcu: __xc_a not in a raw section of %s" % exe)


def emit(fns, src):
    if not fns:      # every initialiser is dead code: nothing for .CRT$XCU (an empty array is not C)
        return "/* generated by tools/msvcw/crt_xcu.py from %s: all initialisers of __xc_a..__xc_z are dead code (zeroed in the VC7 link too), CC=v143 only */\ntypedef int mfl_xcu_none;\n" % os.path.basename(src)
    return ("/* generated by tools/msvcw/crt_xcu.py from %s (__xc_a..__xc_z): the game's initialisers in table order, CC=v143 only */\n" % os.path.basename(src)
            + "#pragma section(\".CRT$XCU\", read)\ntypedef void (__cdecl *mfl_xcu_fn)(void);\n"
            + "".join("extern void __cdecl func_0x%08x(void);\n" % f for f in fns)
            + "__declspec(allocate(\".CRT$XCU\")) const mfl_xcu_fn mfl_xcu_table[%d] = {\n" % len(fns)
            + ",\n".join("  func_0x%08x" % f for f in fns) + "\n};\n")


if __name__ == "__main__":
    fns = table(sys.argv[1])
    if len(fns) != WANT: sys.exit("crt_xcu: %d initialisers, expected %d: %s" % (len(fns), WANT, " ".join("%08x" % f for f in fns)))
    dd = dead(); live = [f for f in fns if not any(a <= f < b for a, b in dd)]
    open(sys.argv[2], "w").write(emit(live, sys.argv[1]))
    print("crt_xcu: %d initialisers, %d dead (left out, zeroed in the VC7 link too), %d -> %s" % (len(fns), len(fns) - len(live), len(live), sys.argv[2]))
