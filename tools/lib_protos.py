#!/usr/bin/env python3
"""lib_protos.py: names/MFL_lib_protos.txt = real prototypes for library callees that output/decls.h declares K&R (`extern undefined name();`: the call then loses its arguments
and every double is pushed as a float / dropped: lua_gettop() without L).  Lua 4.0 API (lua.h of Lua 4.0, game addresses from decls.h) + the RenderWare
SDK functions whose SDK prototype resolves (toolchain/rwsdk/include/d3d9).  Pointer parameters are `void *` (the typedefs of the SDK structs are not all in ghidra_types.h).
tools/fix_decls.py (rule `libprotos`) replaces the `extern ... name();` line by this one; diffemu reads the argument count from it (a double = 2 dwords).  Usage: lib_protos.py"""
import os, re
G = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
H = os.path.join(G, "toolchain", "rwsdk", "include", "d3d9")
LUA = {   # name -> prototype tail (game = Lua 4.0, cdecl; lua_State is opaque here)
 "lua_gettop": "int lua_gettop(void *L)", "lua_tonumber": "double lua_tonumber(void *L, int index)", "lua_typename": "const char *lua_typename(void *L, int t)",
 "lua_pushnil": "void lua_pushnil(void *L)", "lua_pushnumber": "void lua_pushnumber(void *L, double n)", "lua_pushlstring": "void lua_pushlstring(void *L, const char *s, unsigned int len)",
 "lua_newtable": "void lua_newtable(void *L)", "lua_setglobal": "void lua_setglobal(void *L, const char *name)", "lua_ref": "int lua_ref(void *L, int lock)",
 "lua_open": "void *lua_open(int stacksize)", "lua_call": "int lua_call(void *L, int nargs, int nresults)", "lua_error": "void lua_error(void *L, const char *s)", "lua_newtag": "int lua_newtag(void *L)"}
decl = {}
for l in open(os.path.join(G, "output", "decls.h"), errors="replace"):
    m = re.match(r"/\*([0-9a-f]{8})\*/ extern (?:(?!__)[\w ]*?)\b(?:__cdecl )?(\w+)\(\);", l)
    if m: decl[m.group(2)] = m.group(1)
sdk = {}
for f in sorted(os.listdir(H)):
    if not f.endswith(".h"): continue
    t = re.sub(r"/\*.*?\*/|//[^\n]*", " ", open(os.path.join(H, f), errors="replace").read(), flags=re.S)
    t = re.sub(r"^\s*#.*(?:\\\n.*)*$", " ", t, flags=re.M)
    for m in re.finditer(r"(?:^|;|\})\s*(?:extern\s+)?((?:const\s+)?[A-Za-z_]\w*(?:\s*\*+\s*|\s+)(?:\*\s*)*)(\w+)\s*\(([^()]*)\)\s*;", t):
        sdk.setdefault(m.group(2), (" ".join(m.group(1).split()), " ".join(m.group(3).split())))
OK = {"void", "int", "char", "short", "float", "double", "unsigned", "long", "RwInt32", "RwBool", "RwReal", "RwUInt32", "RwInt16", "RwUInt16", "RwUInt8", "RwInt8", "RwChar", "const", "RwFixed", "size_t"}
def conv(p):
    p = p.strip()
    if p in ("", "void"): return []
    out = []
    for a in re.split(r",", p):
        a = " ".join(a.split())
        if "(" in a or "..." in a: return None
        if "*" in a: out.append("void *"); continue
        ws = a.split()
        ty = " ".join(w for w in ws[:-1]) if len(ws) > 1 else ws[0]
        if not set(ty.split()) <= OK: return None      # struct / enum by value, unknown typedef
        out.append(ty)
    return out
lines = []
for n, va in sorted(decl.items(), key=lambda x: x[1]):
    if n in LUA: lines.append("/*%s*/ extern %s;" % (va, LUA[n].replace(" " + n + "(", " __cdecl " + n + "(", 1) if "*" not in LUA[n].split(n)[0] else LUA[n].replace(n + "(", "__cdecl " + n + "(", 1)))
    elif n in sdk:
        rt, ps = sdk[n]; pl = conv(ps)
        if pl is None or ("*" in rt and False): continue
        rt = "void *" if "*" in rt else rt
        if not set(rt.replace("const", "").split()) <= OK: continue
        lines.append("/*%s*/ extern %s __cdecl %s(%s);" % (va, rt.strip(), n, ", ".join("%s p%d" % (t, i) for i, t in enumerate(pl)) or "void"))
open(os.path.join(G, "names", "MFL_lib_protos.txt"), "w").write("# generated by tools/lib_protos.py: real prototypes of K&R-declared library callees (Lua 4.0 API, RenderWare SDK)\n" + "\n".join(lines) + "\n")
print(len(lines), "prototypes,", sum(1 for l in lines if " lua_" in l), "Lua")
