#!/usr/bin/env python3
"""res_extract.py <exe> <outdir>: write mfl.rc + bitmaps/<id>.bmp + rwtexdict_404.txd (+ bin/ for any resource kept binary).
Numeric styles and ids (no windows.h). Original resources are copyrighted game data: keep <outdir> out of git/exports (output/res/ is ignored)."""
import os, struct, sys
from rsrc import entries

BUTTONS = {0x80: "Button", 0x81: "Edit", 0x82: "Static", 0x83: "ListBox", 0x84: "ScrollBar", 0x85: "ComboBox"}
q = lambda s: '"' + s.replace("\\", "\\\\").replace('"', '""') + '"'

def wz(b, p):
    e = p
    while b[e:e + 2] != b"\0\0": e += 2
    return b[p:e].decode("utf-16le"), e + 2

def ordname(b, p):   # sz_Or_Ord
    if struct.unpack_from("<H", b, p)[0] == 0xffff: return struct.unpack_from("<H", b, p + 2)[0], p + 4
    return wz(b, p)

def menu_items(b, p, ind):
    out = []
    while True:
        fl = struct.unpack_from("<H", b, p)[0]; p += 2
        if fl & 0x10:   # popup: no id
            s, p = wz(b, p); sub, p = menu_items(b, p, ind + "    ")
            out.append(None); out[-1] = ind + "POPUP %s" % q(s) + _fl(fl, 0x90) + "\n" + ind + "BEGIN\n" + sub + ind + "END\n"
        else:
            i = struct.unpack_from("<H", b, p)[0]; s, p = wz(b, p + 2)
            out.append(ind + ("MENUITEM SEPARATOR\n" if fl == 0 and i == 0 and s == "" else "MENUITEM %s, %d%s\n" % (q(s), i, _fl(fl, 0x80))))
        if fl & 0x80: return "".join(out), p

NAMES = {0x1: "GRAYED", 0x2: "INACTIVE", 0x4: "BITMAP", 0x8: "CHECKED", 0x20: "MENUBARBREAK", 0x40: "MENUBREAK", 0x100: "OWNERDRAW"}
def _fl(fl, mask):
    fl &= ~mask
    return "".join(", " + n for k, n in NAMES.items() if fl & k) + "".join([", 0x%x" % (fl & ~sum(NAMES))] if fl & ~sum(NAMES) else [])

def menu_rc(i, b):
    ver, hdr = struct.unpack_from("<HH", b, 0); assert ver == 0 and hdr == 0
    s, _ = menu_items(b, 4, "    ")
    return "%d MENU\nBEGIN\n%sEND\n" % (i, s)

def dialog_rc(i, b):
    ver, sig, hid, ex, st, n, x, y, cx, cy = struct.unpack_from("<HHIIIHhhhh", b, 0); assert (ver, sig) == (1, 0xffff)
    p = 26; menu, p = ordname(b, p); cls, p = ordname(b, p); title, p = wz(b, p)
    r = "%d DIALOGEX %d, %d, %d, %d, %d\nSTYLE 0x%08x\nEXSTYLE 0x%x\n" % (i, x, y, cx, cy, hid, st, ex)
    if title: r += "CAPTION %s\n" % q(title)
    if menu: r += "MENU %s\n" % menu
    if cls: r += "CLASS %s\n" % (q(cls) if isinstance(cls, str) else cls)
    if st & 0x40:
        pt, wt, it, cs = struct.unpack_from("<HHBB", b, p); fn, p = wz(b, p + 6)
        r += "FONT %d, %s, %d, %d, %d\n" % (pt, q(fn), wt, it, cs)
    r += "BEGIN\n"
    for _ in range(n):
        p = (p + 3) & ~3
        h, ex, st, x, y, cx, cy, cid = struct.unpack_from("<IIIhhhhi", b, p); p += 24
        c, p = ordname(b, p); t, p = ordname(b, p); ed = struct.unpack_from("<H", b, p)[0]; p += 2
        assert ed == 0 and isinstance(c, int) and c in BUTTONS
        r += "    CONTROL %s, %d, %s, 0x%08x, %d, %d, %d, %d, 0x%x, %d\n" % (q(t) if isinstance(t, str) else "%d" % t, cid, q(BUTTONS[c]), st, x, y, cx, cy, ex, h)
    return r + "END\n"

def strings_rc(blocks):
    r = "STRINGTABLE\nBEGIN\n"
    for bid, b in sorted(blocks.items()):
        p = 0
        for k in range(16):
            n = struct.unpack_from("<H", b, p)[0]; s = b[p + 2:p + 2 + 2 * n].decode("utf-16le"); p += 2 + 2 * n
            if n: r += "    %d, %s\n" % ((bid - 1) * 16 + k, q(s))
        assert p == len(b)
    return r + "END\n"

def main(exe, out):
    E = entries(exe); langs = {k[2] for k in E}; assert len(langs) == 1
    lang = langs.pop(); os.makedirs(out + "/bitmaps", exist_ok=True); os.makedirs(out + "/bin", exist_ok=True)
    rc = "// generated by tools/res/res_extract.py from the original exe (do not edit)\nLANGUAGE %d, %d\n#pragma code_page(1252)\n\n" % (lang & 0x3ff, lang >> 10)
    strs, raw = {}, []
    for (t, n, l), d in sorted(E.items(), key=lambda kv: (str(kv[0][0]), str(kv[0][1]))):
        if t == 2:
            # BITMAPFILEHEADER; the DIB header size field tells where the pixel data starts
            hs, bpp, ncol = struct.unpack_from("<I12xHxx16xI", d, 0)[0], struct.unpack_from("<H", d, 14)[0], struct.unpack_from("<I", d, 32)[0]
            nc = ncol or ((1 << bpp) if bpp <= 8 else 0)
            open("%s/bitmaps/%d.bmp" % (out, n), "wb").write(b"BM" + struct.pack("<IHHI", 14 + len(d), 0, 0, 14 + hs + 4 * nc) + d)
            rc += "%d BITMAP \"bitmaps/%d.bmp\"\n" % (n, n)
        elif t == "RWTEXDICTIONARY":
            open(out + "/rwtexdict_404.txd", "wb").write(d); rc += "%d RWTEXDICTIONARY \"rwtexdict_404.txd\"\n" % n
        elif t == 6: strs[n] = d
        elif t in (4, 5):
            try: txt = (menu_rc if t == 4 else dialog_rc)(n, d)
            except Exception as e: print("binary fallback", t, n, e, file=sys.stderr); txt = None
            if txt: rc += "\n" + txt
            else: raw.append((t, n, d))
        else: raw.append((t, n, d))
    for t, n, d in raw:
        open("%s/bin/%d_%s.bin" % (out, t, n), "wb").write(d); rc += "%s %s \"bin/%s_%s.bin\"\n" % (n, t, t, n)
    rc += "\n" + strings_rc(strs)
    open(out + "/mfl.rc", "w", newline="\n", encoding="cp1252").write(rc)

if __name__ == "__main__": main(*sys.argv[1:3])
