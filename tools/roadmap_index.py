#!/usr/bin/env python3
"""roadmap_index.py: writes ROADMAP-INDEX.md (open items of ROADMAP.md newest first + the verifier tool map, at most 80 lines)
and TOOL-INDEX.md (every tool under tools/ with the first line of its docstring / header comment, newest file first per directory).
Both files are GENERATED: never edit them by hand, rerun this script after ROADMAP.md or tools/ change."""
import ast, os, re, sys, warnings
warnings.simplefilter("ignore", SyntaxWarning)      # ast.parse of tools with old-style escapes in their strings
G = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
CAP, W = 80, 170
HEAD = re.compile(r"^(##+) +(.*)")
OPEN = re.compile(r"^[-* ]*(?:\*\*)?((?:Open|Next|Not done|Handoff|Left open|Still open|Remaining|Follow-ups?|Not attempted|Blocked)\b[^:]{0,40}?):(?:\*\*)? *(.*)", re.I)
NOTHING = re.compile(r"^(none( open| left)?|nothing( open)?|done)\.?$", re.I)
SKIP_DIRS = ("__pycache__", "specs", "scenarios")      # per-run specs and scenario scripts: listed by their driver tools

def clip(s, n=W):
    s = re.sub(r"\s+", " ", s).strip()
    return s if len(s) <= n else s[:n - 3] + "..."

def sections(path):
    """[(heading, line number, [open lines])] in file order"""
    out = []
    for i, l in enumerate(open(path, errors="replace"), 1):
        m = HEAD.match(l)
        if m: out.append((m.group(2).strip(), i, [])); continue
        m = OPEN.match(l)
        if m and out and not NOTHING.match(m.group(2).strip()): out[-1][2].append("%s: %s" % (m.group(1), m.group(2)))
    return out

def describe(p):
    t = open(p, errors="replace").read()
    if p.endswith(".py"):
        try:
            d = ast.get_docstring(ast.parse(t))
            if d: return clip(d.strip().splitlines()[0], 150)
        except SyntaxError: pass
    for l in t.splitlines()[:15]:
        l = l.strip()
        if l.startswith("#") and not l.startswith("#!") and len(l) > 3: return clip(l.lstrip("# "), 150)
    return "(no description)"

def tools():
    """{dir: [(mtime, rel path, description)] newest first}"""
    out = {}
    for d, subs, fs in os.walk(os.path.join(G, "tools")):
        subs[:] = sorted(s for s in subs if s not in SKIP_DIRS)
        for f in fs:
            if f.endswith((".py", ".sh")):
                p = os.path.join(d, f); out.setdefault(os.path.relpath(d, G), []).append((os.path.getmtime(p), os.path.relpath(p, G), describe(p)))
    return {k: sorted(v, reverse=True) for k, v in sorted(out.items())}

def main():
    sys.path.insert(0, os.path.join(G, "tools")); from verify_pins import PINNED
    T = tools()
    tmap = ["## Verifier tool map (pinned by tools/verify_pins.py; all %d tools: TOOL-INDEX.md)" % sum(len(v) for v in T.values())]
    tmap += ["- `%s`: %s" % (p, clip(describe(os.path.join(G, p)), 120)) for p in PINNED if os.path.exists(os.path.join(G, p))]
    tmap += ["- Rules for agents: agent_rules.md in the project scratch area; plan: PLAN-NEW-TECHNIQUES.md (FINAL EXECUTION ORDER)."]
    head = ["# ROADMAP index (GENERATED by tools/roadmap_index.py, do not edit; full history: ROADMAP.md)", "",
            "## Open items, newest first (ROADMAP.md line: heading, then its Open / Next / Not done / Handoff lines)"]
    budget = CAP - len(head) - len(tmap) - 1; body = []
    for h, ln, items in reversed(sections(os.path.join(G, "ROADMAP.md"))):
        if not items: continue
        block = ["- L%d **%s**" % (ln, clip(h, 120))] + ["  - " + clip(x) for x in items[-2:]]
        if len(body) + len(block) > budget: break
        body += block
    lines = head + body + [""] + tmap
    assert len(lines) <= CAP, len(lines)
    open(os.path.join(G, "ROADMAP-INDEX.md"), "w").write("\n".join(lines) + "\n")
    ti = ["# Tool index (GENERATED by tools/roadmap_index.py, do not edit)", "",
          "One line per tool: path, first line of its docstring / header comment. Newest file first in each directory.", ""]
    for d, v in T.items():
        ti += ["## %s (%d)" % (d, len(v))] + ["- `%s`: %s" % (p, s) for _, p, s in v] + [""]
    open(os.path.join(G, "TOOL-INDEX.md"), "w").write("\n".join(ti))
    print("ROADMAP-INDEX.md %d lines, TOOL-INDEX.md %d tools" % (len(lines), sum(len(v) for v in T.values())))

if __name__ == "__main__":
    main()
