#!/usr/bin/env python3
"""plugin_map.py > output/rwp_plugin_map.md: structure map of the Rwp physics plugin block (0x569b30-0x58c8a0).
Per function: size, x87 instruction count, direct callees, indirect calls, vtable slots that point at it; per object file (output/rwp_files.csv): totals and lift order.
Needs objdump; reads game/MFL.exe (or $MFL_EXE) and tools/cmpfn.FNSZ (Ghidra function sizes)."""
import collections, csv, os, re, struct, subprocess, sys, tempfile
G = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."); os.chdir(G); sys.path.insert(0, "tools")
import cmpfn
LO, HI = 0x569b30, 0x58c8a0
GAME = [(int(r["lo"], 16), int(r["hi"], 16)) for r in csv.DictReader(open("output/delink_sdk/ownership_items.csv")) if r["owner"] == "game" and LO <= int(r["lo"], 16) < HI]
def is_game(a): return any(lo <= a < hi for lo, hi in GAME)
fns = None; size = {}      # filled below after the first disassembly pass
names = {int(r[0], 16): r[1] for r in csv.reader(l for l in open("output/rwp_names.csv") if not l.startswith("#"))}
files = [(r["source_file"], int(r["code_start"], 16), int(r["code_end"], 16), r["confidence"]) for r in csv.DictReader(open("output/rwp_files.csv"))]
def file_of(a):
    for f, lo, hi, c in files:
        if lo <= a < hi: return f
    return "?"
code = b"".join(cmpfn.exe_bytes(v, size[v]) for v in [fns[0]]) if False else cmpfn.exe_bytes(LO, HI - LO)
open(tmp := tempfile.mktemp(), "wb").write(code)
dis = subprocess.run(["objdump", "-D", "-M", "intel", "-b", "binary", "-mi386", "--adjust-vma=%d" % LO, tmp], capture_output=True, text=True).stdout; os.unlink(tmp)
ins = []
for l in dis.split("\n"):
    m = re.match(r"\s*([0-9a-f]+):\t([0-9a-f ]+)\t(\S+)\s*(.*)", l)
    if m: ins.append((int(m.group(1), 16), m.group(3), m.group(4)))
import bisect
# function starts = Ghidra functions + ownership items + direct call targets + vtable targets (Ghidra misses ~20% of the entry points that only vtables reach)
exe = open(os.environ.get("MFL_EXE", "game/MFL.exe"), "rb").read()
pe = struct.unpack_from("<I", exe, 0x3c)[0]; ns = struct.unpack_from("<H", exe, pe + 6)[0]; so = pe + 24 + struct.unpack_from("<H", exe, pe + 20)[0]
secs = [struct.unpack_from("<8sIIII", exe, so + 40 * i) for i in range(ns)]
base = struct.unpack_from("<I", exe, pe + 52)[0]
def rva2off(v):
    for n, vs, va, rs, ro in secs:
        if va <= v - base < va + rs: return ro + v - base - va
starts = set(v for v in cmpfn.FNSZ if LO <= v < HI)
starts |= set(int(r["lo"], 16) for r in csv.DictReader(open("output/delink_sdk/ownership_items.csv")) if LO <= int(r["lo"], 16) < HI and not r["name"].startswith("gap_"))
for a, mn, op in ins:
    m = re.match(r"0x([0-9a-f]+)$", op)
    if mn == "call" and m and LO <= int(m.group(1), 16) < HI: starts.add(int(m.group(1), 16))
for va in range(0x5f6000, 0x5f9000, 4):
    o = rva2off(va)
    if o is not None and LO <= struct.unpack_from("<I", exe, o)[0] < HI: starts.add(struct.unpack_from("<I", exe, o)[0])
fns = sorted(starts)
for i, v in enumerate(fns):
    end = fns[i + 1] if i + 1 < len(fns) else HI
    b = cmpfn.exe_bytes(v, end - v)
    while len(b) > 1 and b[-1] in (0xcc, 0x90, 0x00): b = b[:-1]
    size[v] = len(b)
info = {v: dict(ins=0, x87=0, calls=set(), ind=0, jt=0, ext=set()) for v in fns}
def owner(a):
    k = bisect.bisect_right(fns, a) - 1
    return fns[k] if k >= 0 and a < fns[k] + size[fns[k]] + 16 else None
for a, mn, op in ins:
    f = owner(a)
    if f is None: continue
    d = info[f]; d["ins"] += 1
    if mn.startswith("f") and mn not in ("fs",): d["x87"] += 1
    if mn == "call":
        m = re.match(r"0x([0-9a-f]+)$", op)
        if m:
            t = int(m.group(1), 16)
            (d["calls"] if LO <= t < HI else d["ext"]).add(t)
        else: d["ind"] += 1
    if mn == "jmp" and "*" in op: d["jt"] += 1
# vtables in .data: runs of >=2 consecutive dwords pointing into the block
dstart, dend = 0x5f6000, 0x5f9000
slots = {}
for va in range(dstart, dend, 4):
    o = rva2off(va)
    if o is None: continue
    t = struct.unpack_from("<I", exe, o)[0]
    if LO <= t < HI: slots[va] = t
tables, cur = [], []
for va in sorted(slots):
    if cur and va != cur[-1] + 4: tables.append(cur); cur = []
    cur.append(va)
if cur: tables.append(cur)
slot_of = collections.defaultdict(list)
for va, t in slots.items(): slot_of[t].append(va)
callers = collections.defaultdict(set)
for f, d in info.items():
    for t in d["calls"]: callers[t].add(f)
# game-side entry points: calls from outside the block
game_calls = collections.defaultdict(set)
for a, mn, op in [(0, 0, 0)] if False else []: pass
out = []
P = out.append
PLAN = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "plugin_plan.md")).read()
tot = sum(size[f] for f in fns); tx = sum(info[f]["x87"] for f in fns)
P("# Rwp physics plugin map (0x%x-0x%x)\n" % (LO, HI))
P("Generated by `tools/rwp/plugin_map.py`. Function starts = Ghidra functions + ownership items + direct call targets + vtable targets, size = up to the next start minus padding. File boundaries are the RCS link-order proposal of `output/rwp_files.csv` (confidence column), function boundaries are the Ghidra function list.\n")
P("Totals: %d functions, %d bytes (%.1f KB), %d x87 instructions, %d vtable slots in %d tables, %d indirect calls, %d indirect jumps (jump tables / vtable dispatch).\n" % (len(fns), tot, tot / 1024, tx, len(slots), len(tables), sum(i["ind"] for i in info.values()), sum(i["jt"] for i in info.values())))
P("## Object files (link order)\n")
P("| file | range | conf | fns | bytes | of which game-owned | x87 ins | ind. calls | vtable slots | callees in other files |")
P("|---|---|---|---|---|---|---|---|---|---|")
per = collections.OrderedDict()
for f, lo, hi, c in files:
    m = [v for v in fns if lo <= v < hi]
    ext = set(t for v in m for t in info[v]["calls"] if not (lo <= t < hi))
    extf = collections.Counter(file_of(t) for t in ext)
    per[f] = (lo, hi, c, m, extf)
    P("| %s | %x-%x | %s | %d | %d | %d | %d | %d | %d | %s |" % (f, lo, hi, c, len(m), sum(size[v] for v in m), sum(size[v] for v in m if is_game(v)), sum(info[v]["x87"] for v in m), sum(info[v]["ind"] for v in m), sum(len(slot_of[v]) for v in m), ", ".join("%s:%d" % kv for kv in extf.most_common(4))))
P("\n## Vtables / function tables in .data\n")
P("| table VA | slots | targets (file: fn) |"); P("|---|---|---|")
for t in tables:
    P("| %x | %d | %s |" % (t[0], len(t), " ".join("%x" % slots[v] for v in t)))
P("\n(Reading: consecutive dwords that all point into the block; the first tables per volume type are the shape virtuals, the others are object/body/ragdoll tables. Slot meaning is not named yet.)\n")
P("## Function list\n")
P("| VA | size | x87 | calls | ind | callers | vt slots | file | owner | name |"); P("|---|---|---|---|---|---|---|---|---|---|")
for v in fns:
    d = info[v]
    P("| %x | %d | %d | %d | %d | %d | %s | %s | %s | %s |" % (v, size[v], d["x87"], len(d["calls"]), d["ind"], len(callers[v]), " ".join("%x" % s for s in slot_of[v]) or "", file_of(v), "game" if is_game(v) else "", names.get(v, "")))
# lift order: leaves first
P("\n## Game-owned islands\n")
isl = [(v, size[v]) for v in fns if is_game(v)]
P("%d functions / %d bytes inside the block are tagged `game` by output/delink_sdk/ownership_items.csv (heuristic: no RW library match), spanning 56e890-571840. That tag is WEAK: the only external callees of 56e250-571e00 are RtQuatConvertFromMatrix and RwV3dLength, vtable 5f6728 (Cylinder) and 5f6740 point into it, and the RCS order puts RwpMath/RwpCylinder there. Treat the span as Rwp unless a function proves otherwise (the earlier probe note calling it game code was based on the tag)." % (len(isl), sum(s for _, s in isl)))
P("\n## Size distribution\n")
b = collections.Counter(("<64" if size[v] < 64 else "<256" if size[v] < 256 else "<1K" if size[v] < 1024 else "<4K" if size[v] < 4096 else ">=4K") for v in fns)
P(", ".join("%s: %d" % (k, b[k]) for k in ["<64", "<256", "<1K", "<4K", ">=4K"]))
P("\nLargest: " + ", ".join("%x(%d)" % (v, size[v]) for v in sorted(fns, key=lambda v: -size[v])[:12]))
bx = collections.OrderedDict((k, [v for v in fns if lo <= info[v]["x87"] <= hi]) for k, (lo, hi) in [("x87 = 0", (0, 0)), ("x87 1-9", (1, 9)), ("x87 10-49", (10, 49)), ("x87 50+", (50, 10**9))])
P("\n## x87 profile (the byte-identity predictor)\n")
P("| bucket | functions | bytes |"); P("|---|---|---|")
for k, m in bx.items(): P("| %s | %d | %d |" % (k, len(m), sum(size[v] for v in m)))
leaf = [v for v in fns if not info[v]["calls"] and not info[v]["ind"]]
P("\nLeaf functions (no calls inside the block, no indirect calls): %d, %d bytes, %d x87-free." % (len(leaf), sum(size[v] for v in leaf), sum(1 for v in leaf if not info[v]["x87"])))
P(PLAN)
sys.stdout.write("\n".join(out) + "\n")
