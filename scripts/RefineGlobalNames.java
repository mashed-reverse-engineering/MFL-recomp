//Refine auto named globals g_<subsystem>_<hex6> to g_<word1>_<word2>_<hex6> when every function that references the global is descriptively named and shares its first two name words.
//Args: [<csv out>]
//@category Mashed
import java.io.*;
import java.util.*;
import java.util.regex.*;
import ghidra.app.script.GhidraScript;
import ghidra.program.model.listing.*;
import ghidra.program.model.symbol.*;

public class RefineGlobalNames extends GhidraScript {
    static final Pattern AUTO = Pattern.compile("^g_[a-z0-9]+_([0-9a-f]{6})$");

    String words(String fn) {
        if (fn.startsWith("FUN_") || fn.startsWith("thunk_") || fn.contains("_fn_")) return null;
        int sub = fn.indexOf("_sub_");
        if (sub > 0) fn = fn.substring(0, sub);
        String s = fn.replaceFirst("^_+", "").toLowerCase().replaceAll("[^a-z0-9_]", "_");
        String[] t = s.split("_+");
        if (t.length < 2) return null;
        return t[0] + "_" + t[1];
    }

    @Override
    protected void run() throws Exception {
        StringBuilder csv = new StringBuilder("# address,name  (generated by RefineGlobalNames.java)\n");
        ReferenceManager rm = currentProgram.getReferenceManager();
        List<Symbol> syms = new ArrayList<>();
        for (Symbol s : currentProgram.getSymbolTable().getAllSymbols(true))
            if (s.isPrimary() && AUTO.matcher(s.getName()).matches()) syms.add(s);
        int n = 0;
        for (Symbol s : syms) {
            Matcher m = AUTO.matcher(s.getName());
            m.matches();
            String hex = m.group(1);
            String common = null;
            boolean ok = true;
            int refs = 0;
            for (Reference r : rm.getReferencesTo(s.getAddress())) {
                Function f = getFunctionContaining(r.getFromAddress());
                if (f == null) continue;
                String w = words(f.getName());
                if (w == null) { ok = false; break; }
                if (common == null) common = w; else if (!common.equals(w)) { ok = false; break; }
                refs++;
            }
            if (!ok || common == null || refs < 1) continue;
            String name = "g_" + common + "_" + hex;
            if (common.matches(".*[0-9a-f]{6,}.*")) continue;
            try { s.setName(name, SourceType.USER_DEFINED); } catch (Exception e) { continue; }
            csv.append(String.format("%08x,%s%n", s.getAddress().getOffset(), name));
            n++;
        }
        if (getScriptArgs().length > 0) try (FileWriter w = new FileWriter(getScriptArgs()[0])) { w.write(csv.toString()); }
        println("refined " + n + " of " + syms.size() + " globals");
    }
}
