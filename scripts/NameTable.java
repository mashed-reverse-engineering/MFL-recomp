//Name the code pointers of a table of records that start with a name string. Args: <table> <stride> <count> <nameLen> <firstCbOffset> <cbCount> <prefix> [<csv out>]
//  record: char name[nameLen] ... code pointers at firstCbOffset + 4 * slot; function names become <prefix><name lowercase>_cb<slot>
//  Only functions that are still FUN_* are renamed; a pointer shared by several records keeps the first name; the engine's nop stub is skipped.
//@category Mashed
import java.io.*;
import java.util.*;
import ghidra.app.script.GhidraScript;
import ghidra.program.model.address.Address;
import ghidra.program.model.listing.Function;
import ghidra.program.model.symbol.SourceType;

public class NameTable extends GhidraScript {
    @Override
    protected void run() throws Exception {
        String[] a = getScriptArgs();
        Address base = toAddr(Long.decode("0x" + a[0]));
        int stride = Integer.decode("0x" + a[1]), count = Integer.parseInt(a[2]), nameLen = Integer.parseInt(a[3]);
        int first = Integer.decode("0x" + a[4]), cbs = Integer.parseInt(a[5]);
        String prefix = a[6];
        StringBuilder csv = new StringBuilder("# address,name,comment  (generated by NameTable.java)\n");
        Set<Long> done = new HashSet<>();
        int n = 0;
        for (int i = 0; i < count; i++) {
            Address rec = base.add((long) i * stride);
            StringBuilder nm = new StringBuilder();
            for (int k = 0; k < nameLen; k++) {
                int c = getByte(rec.add(k)) & 0xff;
                if (c == 0) break;
                nm.append((char) c);
            }
            String name = nm.toString().toLowerCase().replaceAll("[^a-z0-9_]", "_");
            for (int s = 0; s < cbs; s++) {
                long target = getInt(rec.add(first + 4L * s)) & 0xffffffffL;
                if (target < 0x401000L || target == 0x50B5E0L || !done.add(target)) continue;
                Address t = toAddr(target);
                Function f = getFunctionAt(t);
                if (f == null) { disassemble(t); f = createFunction(t, null); }
                if (f == null || !f.getName().startsWith("FUN_")) continue;
                String fn = prefix + name + "_cb" + s;
                f.setName(fn, SourceType.USER_DEFINED);
                csv.append(String.format("%08x,%s,slot %d of record %d (%s)%n", target, fn, s, i, nm));
                n++;
            }
        }
        if (a.length > 7) try (FileWriter w = new FileWriter(a[7])) { w.write(csv.toString()); }
        println("named " + n + " table callbacks");
    }
}
