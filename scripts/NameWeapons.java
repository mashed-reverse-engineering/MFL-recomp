//Name the callbacks of the weapon descriptor table (MFL.exe: 9 entries x 0x40 bytes at 0x60DC20) by slot. Args: [<csv out>]
//Slot meaning (see FORMATS / ghidra README): +4 equip, +8 fire, +0xC is_finished, +0x10 unequip, +0x14 load_assets, +0x18 free_assets,
//+0x1C update, +0x20 clear_effects, +0x24 reset_all, +0x28 race_start, +0x2C/+0x30 hooks, +0x34 ammo_fraction, +0x38 course 33 update, +0x3C course 2 update.
//@category Mashed
import java.io.*;
import java.util.*;
import ghidra.app.script.GhidraScript;
import ghidra.program.model.address.Address;
import ghidra.program.model.listing.Function;
import ghidra.program.model.symbol.SourceType;

public class NameWeapons extends GhidraScript {
    @Override
    protected void run() throws Exception {
        Map<Integer, String> types = new HashMap<>();
        types.put(7, "mortar"); types.put(9, "machinegun"); types.put(0xA, "drum"); types.put(0xB, "rocket");
        types.put(0xC, "mines"); types.put(0x10, "flamethrower"); types.put(0x11, "shotgun"); types.put(0x12, "flashbang"); types.put(0x13, "oil");
        String[] slot = {null, "equip", "fire", "is_finished", "unequip", "load_assets", "free_assets", "update", "clear_effects", "reset_all",
                         "race_start", "hook_2c", "hook_30", "ammo_fraction", "course_33_update", "course_2_update"};
        ghidra.app.decompiler.DecompInterface di = new ghidra.app.decompiler.DecompInterface();
        di.openProgram(currentProgram);
        Address base = toAddr(0x60DC20L);
        ghidra.program.model.data.DataType ws = currentProgram.getDataTypeManager().getDataType("/Mashed/WeaponSlot");
        ghidra.program.model.data.DataType slotType = ws == null ? null : new ghidra.program.model.data.PointerDataType(ws);
        StringBuilder csv = new StringBuilder("# address,name,comment  (generated by NameWeapons.java from the descriptor table at 0x60DC20)\n");
        Set<Long> done = new HashSet<>();
        int n = 0;
        for (int i = 0; i < 9; i++) {
            Address d = base.add(i * 0x40L);
            String w = types.get(getInt(d));
            if (w == null) { printerr("unknown weapon type at " + d); continue; }
            for (int s = 1; s < 16; s++) {
                long target = getInt(d.add(s * 4L)) & 0xffffffffL;
                if (target == 0 || !done.add(target)) continue;
                Address a = toAddr(target);
                Function f = getFunctionAt(a);
                if (f == null) { disassemble(a); f = createFunction(a, null); }
                if (f == null) continue;
                if (slotType != null && (s <= 4 || s == 13)) {
                    try {
                        ghidra.program.model.pcode.HighFunction hf = di.decompileFunction(f, 60, monitor).getHighFunction();
                        ghidra.program.model.pcode.HighSymbol hs = null;
                        Iterator<ghidra.program.model.pcode.HighSymbol> it = hf.getLocalSymbolMap().getSymbols();
                        while (it.hasNext()) { ghidra.program.model.pcode.HighSymbol x = it.next(); if (x.getName().equals("param_1")) hs = x; }
                        if (hs != null) ghidra.program.model.pcode.HighFunctionDBUtil.updateDBVariable(hs, null, slotType, SourceType.USER_DEFINED);
                    } catch (Exception e) { printerr("param type at " + a + ": " + e); }
                }
                String name = target == 0x50B5E0L ? "nop_stub" : "weapon_" + w + "_" + slot[s];
                if (!f.getName().startsWith("FUN_") && !f.getName().startsWith("thunk_FUN_")) continue;
                f.setName(name, SourceType.USER_DEFINED);
                csv.append(String.format("%08x,%s,descriptor slot +0x%x of %s%n", target, name, s * 4, w));
                n++;
            }
        }
        if (getScriptArgs().length > 0) try (FileWriter fw = new FileWriter(getScriptArgs()[0])) { fw.write(csv.toString()); }
        println("named " + n + " weapon callbacks");
    }
}
