//Name and type the floating point constants in .rdata (DAT_* only used by FPU / SSE instructions) after their value: k_f_0_5, k_d_100, ...
//Args: [<csv out>]. Existing non DAT_ labels are kept. Same value at several addresses gets an address suffix after the first.
//@category Mashed
import java.io.*;
import java.util.*;
import ghidra.app.script.GhidraScript;
import ghidra.program.model.address.*;
import ghidra.program.model.data.*;
import ghidra.program.model.listing.*;
import ghidra.program.model.mem.MemoryBlock;
import ghidra.program.model.symbol.*;

public class NameConstants extends GhidraScript {
    String fmt(double v, boolean single) {
        if (Double.isNaN(v) || Double.isInfinite(v)) return "special";
        if (v == Math.rint(v) && Math.abs(v) < 1e9) return String.valueOf((long) v).replace("-", "n");
        String s = single ? Float.toString((float) v) : Double.toString(v);
        return s.replace("-", "n").replace(".", "_").replace("E", "e").replace("+", "");
    }

    @Override
    protected void run() throws Exception {
        MemoryBlock rdata = currentProgram.getMemory().getBlock(".rdata");
        if (rdata == null) { printerr("no .rdata"); return; }
        Listing l = currentProgram.getListing();
        ReferenceManager rm = currentProgram.getReferenceManager();
        Set<String> used = new HashSet<>();
        StringBuilder csv = new StringBuilder("# address,name  (generated by NameConstants.java)\n");
        int nf = 0, nd = 0;
        List<Symbol> syms = new ArrayList<>();
        for (Symbol s : currentProgram.getSymbolTable().getAllSymbols(true)) {
            String sn = s.getName();
            if ((sn.startsWith("DAT_") || sn.startsWith("k_f_") || sn.startsWith("k_d_")) && s.isPrimary() && rdata.contains(s.getAddress())) syms.add(s);
        }
        syms.sort(Comparator.comparing(Symbol::getAddress));
        for (Symbol s : syms) {
            Address a = s.getAddress();
            boolean isFloat = false, isDouble = false, other = false;
            for (Reference r : rm.getReferencesTo(a)) {
                Instruction in = l.getInstructionAt(r.getFromAddress());
                if (in == null) { other = true; continue; }
                String m = in.getMnemonicString().toUpperCase(), t = in.toString().toLowerCase();
                boolean fp = (m.startsWith("F") && !m.startsWith("FILD") && !m.startsWith("FIST") && !m.startsWith("FIADD") && !m.startsWith("FIMUL")
                              && !m.startsWith("FISUB") && !m.startsWith("FIDIV") && !m.startsWith("FICOM"))
                             || m.endsWith("SS") || m.endsWith("SD") || m.equals("COMISS") || m.equals("COMISD") || m.equals("UCOMISS") || m.equals("UCOMISD");
                if (!fp) { other = true; continue; }
                if (t.contains("qword") || m.endsWith("SD")) isDouble = true; else isFloat = true;
            }
            if (other || (isFloat && isDouble) || (!isFloat && !isDouble)) continue;
            String name;
            DataType dt;
            if (isDouble) {
                double v = Double.longBitsToDouble(getLong(a));
                name = "k_d_" + fmt(v, false);
                dt = new DoubleDataType();
            } else {
                float v = Float.intBitsToFloat(getInt(a));
                name = "k_f_" + fmt(v, true);
                dt = new FloatDataType();
            }
            if (name.endsWith("special")) continue;
            if (!used.add(name)) name = name + "_" + Long.toHexString(a.getOffset());
            used.add(name);
            l.clearCodeUnits(a, a.add(dt.getLength() - 1), false);
            l.createData(a, dt);
            s.setName(name, SourceType.USER_DEFINED);
            csv.append(String.format("%08x,%s%n", a.getOffset(), name));
            if (isDouble) nd++; else nf++;
        }
        if (getScriptArgs().length > 0) try (FileWriter w = new FileWriter(getScriptArgs()[0])) { w.write(csv.toString()); }
        println("named " + nf + " float and " + nd + " double constants");
    }
}
