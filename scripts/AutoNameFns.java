//Give every still unnamed (FUN_*) function of an address range a subsystem name <prefix>_fn_<address>, so that no function is anonymous.
//The prefix comes from the named functions it calls (first match wins: sound, hud, particles, weapon, car, ai, lua, rwp) or else from the address region table below.
//Args: [<startHex> <endHex>] (default 401000..4aa000) [<csv out>]. Names that contain "_fn_" are meant to be replaced later by real names.
//@category Mashed
import java.io.*;
import java.util.*;
import ghidra.app.script.GhidraScript;
import ghidra.program.model.address.*;
import ghidra.program.model.listing.*;
import ghidra.program.model.symbol.*;

public class AutoNameFns extends GhidraScript {
    // region start -> prefix (module guesses from the code around the region, see ghidra/README.md)
    static final long[] START = {0x401000, 0x40ab00, 0x40c000, 0x40e600, 0x417000, 0x41b980, 0x421000, 0x42a000, 0x430000, 0x438000, 0x449000, 0x452000,
                                 0x45e800, 0x468800, 0x474000, 0x480000, 0x48d000, 0x48e000, 0x493000, 0x496000, 0x4a0000};
    static final String[] PREFIX = {"scene", "gamesave", "round", "race", "ai", "hudpanel", "game", "course", "ui", "menu", "camera", "course",
                                    "weapon", "sound", "car", "gfx", "course", "rwpcar", "physics", "particles", "app"};

    String category(Function f) {
        Set<String> callees = new HashSet<>();
        for (Address a : f.getBody().getAddresses(true)) {
            for (Reference r : currentProgram.getReferenceManager().getReferencesFrom(a)) {
                if (!r.getReferenceType().isCall()) continue;
                Function c = getFunctionAt(r.getToAddress());
                if (c != null) callees.add(c.getName());
            }
        }
        String[][] rules = {{"sound", "sfx_", "voice_", "sound_"}, {"hud", "text_draw", "draw_rect", "draw_sprite", "hud_"}, {"particles", "particles_"},
                            {"weapon", "weapon_"}, {"car", "car_"}, {"ai", "ai_"}, {"lua", "lua_"}, {"rwp", "rwp_", "trigger_sphere"}};
        for (String[] rule : rules)
            for (String c : callees)
                for (int i = 1; i < rule.length; i++) if (c.startsWith(rule[i])) return rule[0];
        return null;
    }

    @Override
    protected void run() throws Exception {
        String[] a = getScriptArgs();
        long lo = a.length >= 2 ? Long.decode("0x" + a[0]) : 0x401000, hi = a.length >= 2 ? Long.decode("0x" + a[1]) : 0x4aa000;
        StringBuilder csv = new StringBuilder("# address,name  (generated by AutoNameFns.java)\n");
        int n = 0;
        for (Function f : currentProgram.getListing().getFunctions(toAddr(lo), true)) {
            long off = f.getEntryPoint().getOffset();
            if (off >= hi) break;
            if (f.getName().contains("_fn_")) { csv.append(String.format("%08x,%s%n", off, f.getName())); continue; }
            if (!f.getName().startsWith("FUN_") && !f.getName().startsWith("thunk_FUN_")) continue;
            String pre = category(f);
            if (pre == null) {
                int i = 0;
                while (i + 1 < START.length && START[i + 1] <= off) i++;
                pre = PREFIX[i];
            }
            String name = pre + "_fn_" + String.format("%06x", off);
            f.setName(name, SourceType.USER_DEFINED);
            csv.append(String.format("%08x,%s%n", off, name));
            n++;
        }
        if (a.length >= 3) try (FileWriter w = new FileWriter(a[2])) { w.write(csv.toString()); }
        println("auto named " + n + " functions");
    }
}
