//Rename the remaining DAT_<address> globals to g_<subsystem>_<address>, where the subsystem is the most common first name token of the functions that reference the global.
//Args: [<csv out>]. Globals that nothing references keep their name. Names that start with g_ and contain a subsystem are meant to be replaced by real names later.
//@category Mashed
import java.io.*;
import java.util.*;
import ghidra.app.script.GhidraScript;
import ghidra.program.model.listing.*;
import ghidra.program.model.symbol.*;

public class AutoNameGlobals extends GhidraScript {
    String token(String fn) {
        if (fn.startsWith("FUN_") || fn.startsWith("thunk_FUN_")) return null;
        String s = fn.replaceFirst("^_+", "");
        if (s.matches("^(Rw|rw|Rp|rp|Rt|rt|Rx|rx).*")) return s.substring(0, 2).toLowerCase();
        int i = s.indexOf('_');
        String t = (i > 0 ? s.substring(0, i) : s).toLowerCase();
        t = t.replaceAll("[^a-z0-9]", "");
        return t.isEmpty() ? null : t;
    }

    @Override
    protected void run() throws Exception {
        StringBuilder csv = new StringBuilder("# address,name  (generated by AutoNameGlobals.java)\n");
        ReferenceManager rm = currentProgram.getReferenceManager();
        List<Symbol> syms = new ArrayList<>();
        for (Symbol s : currentProgram.getSymbolTable().getAllSymbols(true))
            if (s.getName().startsWith("DAT_") && s.isPrimary()) syms.add(s);
        int n = 0, none = 0;
        for (Symbol s : syms) {
            Map<String, Integer> votes = new HashMap<>();
            for (Reference r : rm.getReferencesTo(s.getAddress())) {
                Function f = getFunctionContaining(r.getFromAddress());
                if (f == null) continue;
                String t = token(f.getName());
                if (t != null) votes.merge(t, 1, Integer::sum);
            }
            String best = "data";
            int bv = 0;
            for (Map.Entry<String, Integer> e : votes.entrySet()) if (e.getValue() > bv) { bv = e.getValue(); best = e.getKey(); }
            if (votes.isEmpty()) none++;
            String name = "g_" + best + "_" + String.format("%06x", s.getAddress().getOffset());
            s.setName(name, SourceType.USER_DEFINED);
            csv.append(String.format("%08x,%s%n", s.getAddress().getOffset(), name));
            n++;
        }
        if (getScriptArgs().length > 0) try (FileWriter w = new FileWriter(getScriptArgs()[0])) { w.write(csv.toString()); }
        println("renamed " + n + " globals (" + none + " without a named referencing function)");
    }
}
